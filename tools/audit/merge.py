#!/usr/bin/env python3
"""merge.py data/*.txt > ../../src/proto/gb_pname_measured.h

Merges the "M <class> <pname> <count>" lines produced by pname_audit on each
native driver (max per pname) into a sorted C table that gb_pname_count_class
consults before its hand-written rules."""
import sys, collections
best = {"getv": {}, "geti_v": {}}
for f in sys.argv[1:]:
    for l in open(f):
        t = l.split()
        if len(t) == 4 and t[0] == "M":
            c, p, n = t[1], int(t[2], 16), int(t[3])
            best[c][p] = max(best[c].get(p, 0), n)
print("/* generated by tools/audit/merge.py from native-driver measurements; do not edit */")
print("#ifndef GB_PNAME_MEASURED_H\n#define GB_PNAME_MEASURED_H\n#include <stdint.h>\n")
print("struct gb_pname_m { uint16_t pname; uint8_t n; };\n")
for c in ("getv", "geti_v"):
    rows = sorted(best[c].items())
    print("static const struct gb_pname_m gb_pname_measured_%s[] = {" % c)
    for p, n in rows:
        print("\t{ 0x%04X, %d }," % (p, n))
    print("};\n#define GB_PNAME_MEASURED_%s_N %d\n" % (c, len(rows)))
print("#endif")
